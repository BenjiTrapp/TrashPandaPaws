"""The brand assets, and the two things that were wrong with them.

The header served `static/trashpanda_logo.png` -- a 677x369 banner of a
round badge on a white field -- into a 38x38 box with
`border-radius:50%`. A 1.83:1 image forced into a square is squashed
horizontally, and the border-radius then cut a circle out of the white
margin, which is why the raccoon in the header looked flattened and
small. A round crop fixed that, but it would have cut the beret off the
top of the artwork that replaced the banner and the hands and the USB
stick off the bottom, which are the point of it. So the header now shows
`static/logo.gif` itself, through the `/logo.gif` route, in a box with
the artwork's own proportions and `object-fit:contain`.

The assets are generated by `tools/make_brand_assets.py` from the
committed artwork, `static/logo.gif`, and that script needs Pillow to
decode it. Nothing here does: this file carries its own PNG reader,
about fifty lines of `zlib` and `struct`, so the suite can check the
committed pixels without trusting the library that wrote them. The
generator is run as a subprocess for the one test that needs it.

What is checked, and why each one:

  * The artwork is committed, and the assets derived from it are square
    and transparent at the corners, and their outlines have not taken on
    the GIF's pink matte colour -- the symptom of a resample that did
    not premultiply, which only the outline pixels can show.
  * `--check` re-derives every asset and compares bytes, so an asset
    edited by hand, or an artwork changed without regenerating, is
    reported rather than shipped.
  * The header shows the whole animated artwork, contained rather than
    cropped or squashed, and the server serves that file to it. The
    wide banner is still served at `/logo.png`, but not to the header.
"""

import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import unittest
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BRAND = REPO / "static"
WEB = REPO / "software" / "c2" / "static"

MASTER = "logo_256.png"
UPSCALE = "logo_512.png"
# What the page links, smallest last.
WEB_SIZES = (128, 64, 32, 16)


class _Png:
    """Just enough PNG to read 8-bit RGB and RGBA pixels back out of a file."""

    def __init__(self, path):
        raw = Path(path).read_bytes()
        if raw[:8] != b"\x89PNG\r\n\x1a\n":
            raise ValueError("%s is not a PNG" % path)
        chunks = {}
        data = bytearray()
        offset = 8
        while offset < len(raw):
            length = struct.unpack(">I", raw[offset:offset + 4])[0]
            kind = raw[offset + 4:offset + 8]
            payload = raw[offset + 8:offset + 8 + length]
            if kind == b"IDAT":
                data += payload
            else:
                chunks[kind] = payload
            offset += 12 + length

        (self.width, self.height, depth, colour,
         compression, filtering, interlace) = struct.unpack(
            ">IIBBBBB", chunks[b"IHDR"])
        if depth != 8 or colour not in (2, 6) or interlace != 0:
            raise ValueError(
                "%s is depth %d colour type %d interlace %d; this reader "
                "handles 8-bit RGB and RGBA only"
                % (path, depth, colour, interlace))
        del compression, filtering
        self.colour = colour
        self.channels = 3 if colour == 2 else 4

        self.pixels = self._unfilter(zlib.decompress(bytes(data)))

    def _unfilter(self, raw):
        bpp = self.channels
        stride = self.width * bpp
        out = bytearray(stride * self.height)
        previous = bytearray(stride)
        position = 0
        for y in range(self.height):
            kind = raw[position]
            position += 1
            line = bytearray(raw[position:position + stride])
            position += stride
            if kind == 0:
                pass
            elif kind == 1:
                for i in range(bpp, stride):
                    line[i] = (line[i] + line[i - bpp]) & 0xFF
            elif kind == 2:
                for i in range(stride):
                    line[i] = (line[i] + previous[i]) & 0xFF
            elif kind == 3:
                for i in range(stride):
                    left = line[i - bpp] if i >= bpp else 0
                    line[i] = (line[i] + ((left + previous[i]) >> 1)) & 0xFF
            elif kind == 4:
                for i in range(stride):
                    a = line[i - bpp] if i >= bpp else 0
                    b = previous[i]
                    c = previous[i - bpp] if i >= bpp else 0
                    p = a + b - c
                    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                    best = a if (pa <= pb and pa <= pc) else (
                        b if pb <= pc else c)
                    line[i] = (line[i] + best) & 0xFF
            else:
                raise ValueError("unknown PNG filter %d" % kind)
            out[y * stride:(y + 1) * stride] = line
            previous = line
        return bytes(out)

    def pixel(self, x, y):
        i = (y * self.width + x) * self.channels
        return tuple(self.pixels[i:i + self.channels])

    def cell(self, index, size):
        """The bytes of one `size`-wide cell of a strip `size` tall.

        Row by row, so it compares equal to the `pixels` of a standalone
        `size` x `size` image of the same picture.
        """
        stride = self.width * self.channels
        step = size * self.channels
        return b"".join(
            self.pixels[y * stride + index * step:
                        y * stride + (index + 1) * step]
            for y in range(size))

    def with_pixel_cleared(self):
        """A copy with pixel (8, 8) set to opaque white: a hand edit."""
        copy = object.__new__(_Png)
        copy.__dict__.update(self.__dict__)
        pixels = bytearray(self.pixels)
        i = (8 * self.width + 8) * self.channels
        pixels[i:i + self.channels] = b"\xff" * self.channels
        copy.pixels = bytes(pixels)
        return copy

    def to_bytes(self):
        """Re-encode, so a test can write back a file it has altered."""
        stride = self.width * self.channels
        raw = bytearray()
        for y in range(self.height):
            raw.append(0)
            raw += self.pixels[y * stride:(y + 1) * stride]

        def chunk(kind, payload):
            return (struct.pack(">I", len(payload)) + kind + payload
                    + struct.pack(">I", zlib.crc32(kind + payload)
                                  & 0xFFFFFFFF))

        return (b"\x89PNG\r\n\x1a\n"
                + chunk(b"IHDR", struct.pack(">IIBBBBB", self.width,
                                             self.height, 8, self.colour,
                                             0, 0, 0))
                + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
                + chunk(b"IEND", b""))


def _page_source():
    return (REPO / "software" / "c2" / "server.py").read_text()


class TestTheAssetsComeFromTheCommittedArtwork(unittest.TestCase):
    def test_the_artwork_is_committed(self):
        raw = (BRAND / "logo.gif").read_bytes()
        self.assertEqual(raw[:6], b"GIF89a")

    def test_the_master_is_square_and_transparent_at_its_corners(self):
        master = _Png(BRAND / MASTER)
        self.assertEqual((master.width, master.height), (256, 256))
        self.assertEqual(master.channels, 4)
        for x, y in ((0, 0), (255, 0), (0, 255), (255, 255)):
            self.assertEqual(master.pixel(x, y)[3], 0)

    def test_the_old_wallpaper_crop_is_gone(self):
        for name in ("raccoon_face_256.png", "raccoon_face_512.png"):
            self.assertFalse((BRAND / name).exists())
        self.assertNotIn("raccoon_face", _page_source())

    def test_the_master_is_not_copied_into_the_served_directory(self):
        # The page links nothing bigger than 128, and a second copy of a
        # 166 kB file is a second thing that can drift. The brand folder
        # is for a README or a slide deck; the served folder carries only
        # what the page asks for.
        self.assertFalse((WEB / MASTER).exists())
        self.assertNotIn(MASTER, _page_source())

    def test_every_linked_size_is_there_with_an_alpha_channel(self):
        for size in WEB_SIZES:
            with self.subTest(size=size):
                image = _Png(WEB / ("favicon-%d.png" % size))
                self.assertEqual((image.width, image.height), (size, size))
                self.assertEqual(image.channels, 4)

    def test_the_matte_colour_has_not_bled_into_the_outline(self):
        # The GIF's transparent pixels carry RGB (224, 106, 108). A
        # resample that did not premultiply would average that pink into
        # every outline pixel, weighted by how much of the pixel is
        # background: the mostly-transparent edge would come out almost
        # entirely pink. Measured on this artwork, 80% or more of the
        # pixels with alpha below 128 are within 40 of the matte colour
        # when the resample is wrong, and 4% or fewer when it is right.
        #
        # It is a proportion and not "none of them", because the raccoon's
        # own fur rim is red: a legitimate edge pixel sits as close as 12
        # to the matte colour, so no per-pixel threshold separates the
        # two. What does is that bleed takes over the whole population.
        matte = (224, 106, 108)
        paths = [BRAND / MASTER] + [WEB / ("favicon-%d.png" % size)
                                    for size in WEB_SIZES]
        for path in paths:
            with self.subTest(asset=path.name):
                image = _Png(path)
                edge = [pixel for pixel in (
                    image.pixel(x, y) for y in range(image.height)
                    for x in range(image.width)) if 0 < pixel[3] < 128]
                self.assertTrue(edge, "no mostly-transparent edge pixels")
                pink = [pixel for pixel in edge
                        if max(abs(c - m) for c, m in zip(pixel, matte)) <= 40]
                self.assertLess(
                    len(pink) / len(edge), 0.10,
                    "%d of %d outline pixels are the GIF's matte colour"
                    % (len(pink), len(edge)))

    def test_the_upscale_is_marked_as_one(self):
        # 512 is a Lanczos upscale and carries no detail the 256 does not.
        # The generator says so; this keeps it from being mistaken for a
        # second master.
        self.assertTrue((BRAND / UPSCALE).exists())
        tool = (REPO / "tools" / "make_brand_assets.py").read_text()
        self.assertIn("Lanczos", tool)
        self.assertIn("upscale", tool.lower())


class TestTheCommittedAssetsAreWhatTheGeneratorMakes(unittest.TestCase):
    TOOL = REPO / "tools" / "make_brand_assets.py"

    def _check(self):
        return subprocess.run([sys.executable, str(self.TOOL), "--check"],
                              capture_output=True, text=True, timeout=300)

    def test_check_reports_every_asset_as_matching(self):
        done = self._check()
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)
        self.assertNotIn("DIFFERS", done.stdout)
        self.assertNotIn("missing", done.stdout)

    def test_check_notices_an_asset_edited_by_hand(self):
        target = WEB / "favicon-16.png"
        original = target.read_bytes()
        try:
            target.write_bytes(_Png(target).with_pixel_cleared().to_bytes())
            done = self._check()
            self.assertNotEqual(done.returncode, 0,
                                "--check passed on an edited asset")
            self.assertIn("DIFFERS", done.stdout)
        finally:
            target.write_bytes(original)


class TestTheFrameStripCarriesTheArtworksOwnAnimation(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.strip = _Png(WEB / "favicon-frames-64.png")
        cls.page = _page_source()

    def test_it_is_eight_square_cells(self):
        self.assertEqual(self.strip.height, 64)
        self.assertEqual(self.strip.width, 8 * 64)
        self.assertEqual(self.strip.channels, 4)

    def test_the_page_expects_exactly_that_many_frames(self):
        # A re-exported artwork with a different frame count must fail
        # here rather than freeze the icon on a half-drawn cell.
        declared = int(re.search(r"const FAVICON_FRAMES = (\d+)",
                                 self.page).group(1))
        self.assertEqual(declared, self.strip.width // self.strip.height)

    def test_consecutive_cells_differ(self):
        for i in range(7):
            with self.subTest(cell=i):
                self.assertNotEqual(self.strip.cell(i, 64),
                                    self.strip.cell(i + 1, 64))

    def test_the_glow_rises_then_falls(self):
        reds = [sum(self.strip.cell(i, 64)[0::4]) for i in range(8)]
        self.assertEqual(reds.index(max(reds)), 4,
                         "the brightest cell is %d, not the still frame"
                         % reds.index(max(reds)))
        self.assertLess(reds[0], reds[4])
        self.assertLess(reds[7], reds[4])

    def test_the_still_favicon_is_the_strips_bright_cell(self):
        # Written as a copy, so the tab's static icon and the animation's
        # brightest frame cannot drift apart.
        self.assertEqual(_Png(WEB / "favicon-64.png").pixels,
                         self.strip.cell(4, 64))


