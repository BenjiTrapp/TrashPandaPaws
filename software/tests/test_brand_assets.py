"""The brand assets, and the two things that were wrong with them.

The header served `static/trashpanda_logo.png` -- a 677x369 banner of a
round badge on a white field -- into a 38x38 box with
`border-radius:50%`. A 1.83:1 image forced into a square is squashed
horizontally, and the border-radius then cut a circle out of the white
margin, which is why the raccoon in the header looked flattened and
small.

The assets are generated by `tools/make_brand_assets.py`, which needs
Pillow to decode the source JPEG. Nothing here does: this file carries
its own PNG reader, about forty lines of `zlib` and `struct`, so the
suite can check the committed pixels without a dependency the project
does not declare.

What is checked, and why each one:

  * The sizes are what the page links, and every one is an **exact 2x2
    average** of the one above it. That is the whole claim behind calling
    the crop pixel-faithful: no filter chose anything.
  * The eye coordinates the favicon animation draws its glow at are
    re-derived from the committed favicon. A crop that moves would
    otherwise leave the glow on the fur, and nothing would say so.
  * The header cannot distort its source again, whatever it is given.
"""

import json
import re
import shutil
import struct
import subprocess
import tempfile
import unittest
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BRAND = REPO / "static"
WEB = REPO / "software" / "c2" / "static"

MASTER = "raccoon_face_256.png"
# What the page links, smallest last. The chain has to halve cleanly from
# the master, which is why these are powers of two.
WEB_SIZES = (128, 64, 32, 16)


class _Png:
    """Just enough PNG to read 8-bit RGB pixels back out of a file."""

    def __init__(self, path):
        raw = Path(path).read_bytes()
        if raw[:8] != b"\x89PNG\r\n\x1a\n":
            raise ValueError("%s is not a PNG" % path)
        chunks = {}
        data = bytearray()
        offset = 8
        while offset < len(raw):
            length = struct.unpack(">I", raw[offset:offset + 4])[0]
            kind = raw[offset + 4:offset + 8]
            payload = raw[offset + 8:offset + 8 + length]
            if kind == b"IDAT":
                data += payload
            else:
                chunks[kind] = payload
            offset += 12 + length

        (self.width, self.height, depth, colour,
         compression, filtering, interlace) = struct.unpack(
            ">IIBBBBB", chunks[b"IHDR"])
        if (depth, colour, interlace) != (8, 2, 0):
            raise ValueError(
                "%s is depth %d colour type %d interlace %d; this reader "
                "handles 8-bit RGB only" % (path, depth, colour, interlace))
        del compression, filtering

        self.pixels = self._unfilter(zlib.decompress(bytes(data)))

    def _unfilter(self, raw):
        stride = self.width * 3
        out = bytearray(stride * self.height)
        previous = bytearray(stride)
        position = 0
        for y in range(self.height):
            kind = raw[position]
            position += 1
            line = bytearray(raw[position:position + stride])
            position += stride
            if kind == 0:
                pass
            elif kind == 1:
                for i in range(3, stride):
                    line[i] = (line[i] + line[i - 3]) & 0xFF
            elif kind == 2:
                for i in range(stride):
                    line[i] = (line[i] + previous[i]) & 0xFF
            elif kind == 3:
                for i in range(stride):
                    left = line[i - 3] if i >= 3 else 0
                    line[i] = (line[i] + ((left + previous[i]) >> 1)) & 0xFF
            elif kind == 4:
                for i in range(stride):
                    a = line[i - 3] if i >= 3 else 0
                    b = previous[i]
                    c = previous[i - 3] if i >= 3 else 0
                    p = a + b - c
                    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                    best = a if (pa <= pb and pa <= pc) else (
                        b if pb <= pc else c)
                    line[i] = (line[i] + best) & 0xFF
            else:
                raise ValueError("unknown PNG filter %d" % kind)
            out[y * stride:(y + 1) * stride] = line
            previous = line
        return bytes(out)

    def pixel(self, x, y):
        i = (y * self.width + x) * 3
        return self.pixels[i], self.pixels[i + 1], self.pixels[i + 2]

    def halved(self):
        """The same 2x2 mean the generator applies, derived independently."""
        w, h = self.width // 2, self.height // 2
        out = bytearray(w * h * 3)
        for y in range(h):
            for x in range(w):
                for channel in range(3):
                    total = 0
                    for dy in (0, 1):
                        for dx in (0, 1):
                            i = (((y * 2 + dy) * self.width)
                                 + (x * 2 + dx)) * 3 + channel
                            total += self.pixels[i]
                    out[(y * w + x) * 3 + channel] = (total + 2) // 4
        return bytes(out)


def _page_source():
    return (REPO / "software" / "c2" / "server.py").read_text()


class TestTheAssetsExistAtTheSizesThePageLinks(unittest.TestCase):
    def test_the_master_is_square_and_native(self):
        master = _Png(BRAND / MASTER)
        self.assertEqual((master.width, master.height), (256, 256))

    def test_the_master_is_not_copied_into_the_served_directory(self):
        # The page links nothing bigger than 128, and a second copy of a
        # 166 kB file is a second thing that can drift. The brand folder
        # is for a README or a slide deck; the served folder carries only
        # what the page asks for.
        self.assertFalse((WEB / MASTER).exists(),
                         "the master is duplicated into the served "
                         "directory, where nothing links it")
        self.assertNotIn(MASTER, _page_source(),
                         "the page links the master after all")

    def test_every_linked_size_is_there(self):
        for size in WEB_SIZES:
            path = WEB / ("favicon-%d.png" % size)
            with self.subTest(size=size):
                self.assertTrue(path.exists(), "%s is missing" % path.name)
                image = _Png(path)
                self.assertEqual((image.width, image.height), (size, size))

    def test_the_upscale_is_marked_as_one(self):
        # 512 is a Lanczos upscale and carries no detail the 256 does not.
        # The generator says so; this keeps it from being mistaken for a
        # second master.
        self.assertTrue((BRAND / "raccoon_face_512.png").exists())
        tool = (REPO / "tools" / "make_brand_assets.py").read_text()
        self.assertIn("Lanczos", tool)
        self.assertIn("upscale", tool.lower())


class TestEverySizeIsAnExactAverageOfTheOneAbove(unittest.TestCase):
    """The claim behind "pixel-faithful", checked rather than asserted.

    No filter chose anything: each smaller size is the arithmetic mean of
    2x2 blocks of the larger. Derived here with this file's own reader, so
    a change to the generator cannot quietly redefine what it means.
    """

    def test_the_whole_chain_halves_cleanly(self):
        above = _Png(BRAND / MASTER)
        for size in WEB_SIZES:
            with self.subTest(size=size):
                expected = above.halved()
                actual = _Png(WEB / ("favicon-%d.png" % size))
                self.assertEqual((actual.width, actual.height), (size, size))
                self.assertEqual(
                    actual.pixels, expected,
                    "favicon-%d.png is not the exact 2x2 average of the "
                    "%dx%d above it" % (size, size * 2, size * 2))
                above = actual

    def test_the_averaging_rounds_rather_than_truncates(self):
        # A chain that truncated would darken by up to 1.5 per channel at
        # every step, which is four steps from 256 to 16.
        tool = (REPO / "tools" / "make_brand_assets.py").read_text()
        self.assertIn("(total + 2) // 4", tool,
                      "the generator no longer rounds to nearest")


class TestTheGlowSitsOnTheEyes(unittest.TestCase):
    """Where the favicon animation draws, against where the eyes are.

    The page carries the coordinates as constants because fetching them
    would be an extra request and a failure mode. This is what keeps them
    true: the eyes are found in the committed favicon the same way the
    generator found them, and compared.
    """

    @classmethod
    def setUpClass(cls):
        cls.page = _page_source()
        cls.favicon = _Png(WEB / "favicon-64.png")

    def _declared(self):
        match = re.search(r"const FAVICON_EYES = \[\[([\d.]+), ([\d.]+)\], "
                          r"\[([\d.]+), ([\d.]+)\]\]", self.page)
        self.assertIsNotNone(match,
                             "the page no longer declares FAVICON_EYES")
        values = [float(g) for g in match.groups()]
        return [(values[0], values[1]), (values[2], values[3])]

    def _measured(self):
        """The two glowing clusters in the favicon, as fractions of it."""
        image = self.favicon
        x0, x1 = int(image.width * 0.20), int(image.width * 0.70)
        y0, y1 = int(image.height * 0.35), int(image.height * 0.55)
        hits = []
        for y in range(y0, y1):
            for x in range(x0, x1):
                r, g, b = image.pixel(x, y)
                if r > 150 and r - max(g, b) > 60:
                    hits.append((x, y))
        self.assertTrue(hits, "no red pixels in the favicon's eye band")
        columns = sorted({x for x, _ in hits})
        gaps = [(b - a, a) for a, b in zip(columns, columns[1:]) if b - a > 2]
        self.assertTrue(gaps, "the red pixels form one cluster, not two eyes")
        split = max(gaps)[1]
        out = []
        for group in ([p for p in hits if p[0] <= split],
                      [p for p in hits if p[0] > split]):
            xs = [p[0] for p in group]
            ys = [p[1] for p in group]
            out.append(((min(xs) + max(xs)) / 2 / image.width,
                        (min(ys) + max(ys)) / 2 / image.height))
        return out

    def test_the_declared_eyes_are_where_the_red_pixels_are(self):
        for declared, measured in zip(self._declared(), self._measured()):
            with self.subTest(declared=declared):
                self.assertAlmostEqual(declared[0], measured[0], delta=0.05,
                                       msg="the glow is %.3f from the left "
                                           "and the eye is %.3f"
                                           % (declared[0], measured[0]))
                self.assertAlmostEqual(declared[1], measured[1], delta=0.05,
                                       msg="the glow is %.3f from the top "
                                           "and the eye is %.3f"
                                           % (declared[1], measured[1]))

    def test_the_radius_is_smaller_than_the_gap_between_the_eyes(self):
        # Otherwise the two glows merge into one smear across the muzzle.
        match = re.search(r"const FAVICON_EYE_RADIUS = ([\d.]+)", self.page)
        self.assertIsNotNone(match)
        radius = float(match.group(1))
        left, right = self._declared()
        self.assertLess(radius * 4, right[0] - left[0],
                        "the glow is wide enough to merge the two eyes")


class TestTheHeaderCannotSquashItsLogoAgain(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.page = _page_source()

    def test_the_header_image_is_cropped_not_stretched(self):
        rule = re.search(r"header img\{[^}]*\}", self.page, re.S)
        self.assertIsNotNone(rule, "the header image rule is gone")
        self.assertIn("object-fit:cover", rule.group(0),
                      "a non-square source would be squashed into the box "
                      "again, which is the defect this replaced")

    def test_the_header_is_given_a_square_source(self):
        match = re.search(r'<img src="(/static/[^"]+)"', self.page)
        self.assertIsNotNone(match, "the header has no image")
        name = match.group(1).rsplit("/", 1)[1]
        image = _Png(WEB / name)
        self.assertEqual(image.width, image.height,
                         "%s is %dx%d, and the header draws it square"
                         % (name, image.width, image.height))

    def test_the_header_no_longer_serves_the_wide_banner(self):
        # `/logo.png` still exists for anything that linked it; the header
        # is what must not use it.
        header = self.page.split("<header>", 1)[1].split("</header>", 1)[0]
        self.assertNotIn("/logo.png", header,
                         "the header is back on the 677x369 banner")


class TestTheAnimationBehaves(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.page = _page_source()
        cls.body = cls.page.split("function animateFavicon()", 1)[1] \
            .split("\nfunction ", 1)[0]

    def test_there_is_a_static_favicon_for_before_the_script_runs(self):
        self.assertIn('<link id="favicon" rel="icon"', self.page)
        self.assertIn('href="/static/favicon-64.png"', self.page,
                      "the static favicon does not point at a real file")
        for size in (32, 16):
            self.assertIn("/static/favicon-%d.png" % size, self.page,
                          "the %dpx favicon is not offered" % size)

    def test_it_stops_drawing_while_the_tab_is_hidden(self):
        # It runs for as long as the console is open, which for an
        # operator is all day.
        self.assertIn("document.hidden", self.body,
                      "the animation redraws a favicon nobody can see")

    def test_a_missing_image_leaves_the_static_favicon_alone(self):
        self.assertIn("onerror", self.body,
                      "a failed image load would leave the tab blank")

    def test_it_gives_up_rather_than_looping_on_a_canvas_error(self):
        # `toDataURL` throws on a tainted canvas, and it would throw every
        # frame. One return is cheaper than ten exceptions a second.
        self.assertIn("toDataURL", self.body)
        self.assertIn("catch", self.body,
                      "a canvas error would be raised ten times a second")


_HARNESS = r"""
// A canvas that draws nothing and records where it would have drawn, so
// the glow's geometry can be checked rather than assumed.
const drawn = [];
const hrefs = [];
const link = { set href(v) { hrefs.push(v); } };
const ctx = {
  globalCompositeOperation: "source-over", fillStyle: null,
  clearRect(){}, drawImage(){}, beginPath(){}, fill(){},
  arc(x, y, r){ drawn.push({x, y, r}); },
  createRadialGradient(){ return { addColorStop(){} }; },
};
const canvas = { width:0, height:0, getContext(){ return ctx; },
                 toDataURL(){ return "data:image/png;base64,FAKE"; } };
global.document = { hidden: false,
  getElementById(id){ return id === "favicon" ? link : null; },
  createElement(){ return canvas; } };
global.window = { HTMLCanvasElement: function(){} };
let image = null;
global.Image = function(){ image = this; };

// The clock, controlled. The pulse has a period of about 2.9 seconds and
// the harness watches for well under one, so with the real clock the
// radius spread depended on which part of the sine the run happened to
// start in -- the spread assertion passed most of the time and failed in
// a full-suite run. Each frame now advances the clock 700 ms, so seven
// frames cover more than a full period whatever the wall clock says.
let fakeNow = 0;
Date.now = function(){ fakeNow += 700; return fakeNow; };

eval(require("fs").readFileSync(process.argv[2], "utf8"));
animateFavicon();
if(!image){ console.log("RESULT " + JSON.stringify({error:"no image requested"})); process.exit(0); }
const src = image.src;
image.onload();
setTimeout(() => {
  const before = drawn.length;
  document.hidden = true;
  setTimeout(() => {
    console.log("RESULT " + JSON.stringify({
      src: src, updates: hrefs.length, href: hrefs[0] || "",
      circles: drawn.slice(0, 2),
      radii: [Math.min.apply(null, drawn.map(c => c.r)),
              Math.max.apply(null, drawn.map(c => c.r))],
      whileHidden: drawn.length - before,
    }));
    // The animation keeps a timer alive even while hidden -- that is the
    // back-off, and it is deliberate. Without this the harness would
    // never return, which it did not, for two minutes.
    process.exit(0);
  }, 700);
}, 650);
"""


@unittest.skipUnless(shutil.which("node"),
                     "node is not on PATH, so the animation can only be "
                     "checked structurally by the class above")
class TestTheAnimationActuallyRuns(unittest.TestCase):
    """The loop, executed rather than read.

    Everything above this checks the page's text and the committed
    pixels, which is the floor and runs everywhere. This runs the
    function in node against a canvas that records what it would have
    drawn, and is the only thing here that can tell "the glow is centred
    on the eyes" from "the constants happen to be written down".

    It skips without node, and a skipped test holds nothing -- which is
    why the structural checks are separate and not folded into this one.
    """

    @classmethod
    def setUpClass(cls):
        page = _page_source()
        start = page.index("const FAVICON_EYES")
        end = page.index("\nfunction esc(s){")
        cls.result = cls._run(page[start:end])

    @staticmethod
    def _run(js):
        with tempfile.TemporaryDirectory() as tmp:
            script = Path(tmp) / "anim.js"
            harness = Path(tmp) / "harness.js"
            script.write_text(js)
            harness.write_text(_HARNESS)
            done = subprocess.run(["node", str(harness), str(script)],
                                  capture_output=True, text=True, timeout=120)
        for line in done.stdout.splitlines():
            if line.startswith("RESULT "):
                return json.loads(line[len("RESULT "):])
        raise AssertionError("the harness printed no result.\nstdout: %s\n"
                             "stderr: %s"
                             % (done.stdout[-600:], done.stderr[-600:]))

    def test_it_loads_the_favicon_it_was_given(self):
        self.assertNotIn("error", self.result, self.result)
        self.assertEqual(self.result["src"], "/static/favicon-64.png")

    def test_it_keeps_replacing_the_icon(self):
        self.assertGreaterEqual(self.result["updates"], 4,
                                "only %d frames in 650 ms"
                                % self.result["updates"])
        self.assertTrue(self.result["href"].startswith("data:image/png"),
                        "the icon was set to %r"
                        % self.result["href"][:40])

    def test_the_glow_is_centred_on_the_eyes(self):
        # 64 is the canvas size the page uses, so a circle at x 21.4 is at
        # 0.334 of the width -- which is where the left eye is.
        page = _page_source()
        match = re.search(r"const FAVICON_EYES = \[\[([\d.]+), ([\d.]+)\], "
                          r"\[([\d.]+), ([\d.]+)\]\]", page)
        declared = [(float(match.group(1)), float(match.group(2))),
                    (float(match.group(3)), float(match.group(4)))]
        circles = self.result["circles"]
        self.assertEqual(len(circles), 2,
                         "a frame drew %d glows, not two" % len(circles))
        for (ex, ey), circle in zip(declared, circles):
            with self.subTest(eye=(ex, ey)):
                self.assertAlmostEqual(circle["x"] / 64, ex, delta=0.01)
                self.assertAlmostEqual(circle["y"] / 64, ey, delta=0.01)

    def test_the_glow_pulses(self):
        # The harness advances a fake clock 700 ms per frame, so the
        # frames it watched span more than one full period of the pulse
        # and the spread is the whole amplitude rather than whatever slice
        # of the sine the wall clock happened to land on. With the real
        # clock this assertion was a coin toss, and it came up tails in a
        # full-suite run.
        low, high = self.result["radii"]
        self.assertGreater(high - low, 2.0,
                           "the radius went from %.2f to %.2f, which is not "
                           "the full pulse" % (low, high))

    def test_it_draws_nothing_while_the_tab_is_hidden(self):
        self.assertEqual(self.result["whileHidden"], 0,
                         "it drew %d more times with the tab hidden"
                         % self.result["whileHidden"])


